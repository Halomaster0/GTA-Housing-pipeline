def dump(obj: dict) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=True) + "\n"


def visual_container(spec: dict, z: int) -> dict:
    x, y, w, h = spec["box"]
    body: dict = {"visualType": spec["visualType"]}
    if spec.get("roles"):
        body["query"] = {
            "queryState": {role: {"projections": projs} for role, projs in spec["roles"].items()}
        }
    if spec.get("objects"):
        body["objects"] = spec["objects"]
    return {
        "$schema": schema("visualContainer"),
        "name": spec["name"],
        "position": {"x": x, "y": y, "z": z, "width": w, "height": h, "tabOrder": z},
        "visual": body,
    }


def build_files() -> dict[str, str]:
    """Every emitted file as {path relative to the Report folder: text}."""
    files: dict[str, str] = {
        f"{DEFINITION}/version.json": dump({"$schema": schema("versionMetadata"), "version": PBIR_VERSION}),
        f"{DEFINITION}/report.json": dump(
            {
                "$schema": schema("report"),
                "themeCollection": {},
                "settings": {"defaultDrillFilterOtherVisuals": True},
            }
        ),
        f"{DEFINITION}/pages/pages.json": dump(
            {
                "$schema": schema("pagesMetadata"),
                "pageOrder": [name for name, _, _ in PAGES],
                "activePageName": PAGES[0][0],
            }
        ),
    }
    for page_name, display, visuals in PAGES:
        base = f"{DEFINITION}/pages/{page_name}"
        files[f"{base}/page.json"] = dump(
            {
                "$schema": schema("page"),
                "name": page_name,
                "displayName": display,
                "displayOption": "FitToPage",
                "height": PAGE_HEIGHT,
                "width": PAGE_WIDTH,
            }
        )
        for z, spec in enumerate(visuals):
            files[f"{base}/visuals/{spec['name']}/visual.json"] = dump(visual_container(spec, z))
    for rel, text in files.items():
        try:
            text.encode("ascii")
        except UnicodeEncodeError as exc:
            raise SystemExit(f"{rel}: non-ASCII character in emitted text") from exc
    return files


def verify(report: Path, files: dict[str, str]) -> int:
    problems: list[str] = []
    for rel, text in files.items():
        target = report / rel
        if not target.is_file():
            problems.append(f"{rel}: missing")
        elif target.read_bytes().decode("utf-8").replace("\r\n", "\n") != text:
            problems.append(f"{rel}: differs from generator output")
    definition = report / DEFINITION
    if definition.is_dir():
        found = {p.relative_to(report).as_posix() for p in definition.rglob("*") if p.is_file()}
        problems += [f"{rel}: not produced by the generator" for rel in sorted(found - set(files))]
    if (report / "report.json").exists():
        problems.append("report.json: legacy report shell present alongside definition/")
    if problems:
        print(f"STALE OUTPUT: {len(problems)} problem(s) under {report}")
        for problem in problems:
            print(f"  - {problem}")
        print("Regenerate with `python scripts/generate_pbir_report.py --force`.")
        return 1
    print(f"OK: {len(files)} report files under {report} match the generator")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT, help="Report folder to write.")
    parser.add_argument("--verify", action="store_true", help="Fail if files differ from the generator.")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing definition/ folder.")
    args = parser.parse_args(argv)

    files = build_files()
    if args.verify:
        return verify(args.report, files)

    definition = args.report / DEFINITION
    if definition.exists() and not args.force:
        print(
            f"{definition} already exists and may hold edits made in Power BI Desktop. "
            "Re-run with --force to overwrite it.",
            file=sys.stderr,
        )
        return 2
    if definition.exists():
        shutil.rmtree(definition)
    for rel, text in files.items():
        target = args.report / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))
    legacy = args.report / "report.json"
    if legacy.exists():
        legacy.unlink()
        print(f"removed legacy {legacy}")
    print(f"wrote {len(files)} files under {definition}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
